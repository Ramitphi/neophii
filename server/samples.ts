function makeSvgThumb(bg: string, accent: string, label: string): string {
  const safe = label.replace(/[<>&"]/g, '');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 200" width="320" height="200">
    <rect width="320" height="200" fill="${bg}" rx="12"/>
    <circle cx="72" cy="76" r="28" fill="${accent}" opacity="0.28"/>
    <rect x="44" y="120" width="232" height="14" rx="7" fill="${accent}" opacity="0.35"/>
    <rect x="44" y="146" width="160" height="10" rx="5" fill="${accent}" opacity="0.2"/>
    <text x="44" y="84" font-family="Georgia, serif" font-size="18" fill="#1e293b">${safe}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

